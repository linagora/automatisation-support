function toExtractableFieldDefinition(
  field: SupportCatalogField
): ExtractableFieldDefinition {
  return {
    fieldName: field.key,
    description: field.description,
    askableByUser: field.askable ?? true
  };
}

function mapFields(
  fields: readonly SupportCatalogField[]
): ExtractableFieldDefinition[] {
  return fields.map(toExtractableFieldDefinition);
}

